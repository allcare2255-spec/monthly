function buildWeek(w: number): WeeklyReport {
  const start = addDays(DEMO_STUDENT.cycleStart, (w - 1) * 7);
  const day_data: DayData[] = Array.from({ length: 7 }, (_, i) => ({
    date: addDays(start, i),
    wake_up_time: WAKE[w - 1][i],
    study_minutes: STUDY[w - 1][i],
    target_study_minutes: TARGET[w - 1][i],
    status: STATUS[w - 1][i],
    memo: null,
    ...(w === DEMO_STUDENT.featuredWeek ? FEATURED_NOTES[i] : {}),
  }));
  const featured = w === DEMO_STUDENT.featuredWeek;
  return {
    id: `demo-week-${w}`,
    student_id: "demo",
    cycle_number: DEMO_STUDENT.cycle,
    week_number: w,
    start_date: start,
    end_date: addDays(start, 6),
    day_data,
    good_points: featured ? WEEKLY_GOOD : null,
    improvement_points: featured ? WEEKLY_IMPROVE : null,
    next_week_actions: featured ? WEEKLY_NEXT : null,
    created_at: start,
    updated_at: start,
  };
}

