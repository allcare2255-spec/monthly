export const DEMO_PLAN_RATE = (() => {
  const keys = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"] as const;
  const perDay = keys.map((k) => ({
    done: DEMO_PLAN.days[k].tasks.filter((x) => x.done).length,
    total: DEMO_PLAN.days[k].tasks.length,
  }));
  const done = perDay.reduce((s, d) => s + d.done, 0);
  const total = perDay.reduce((s, d) => s + d.total, 0);
  return { perDay, percent: Math.round((done / total) * 100) };
})();

